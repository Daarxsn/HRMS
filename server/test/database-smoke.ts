import assert from 'node:assert/strict';
import { pool } from '../src/db.mts';

try {
  const [tables] = await pool.query('SELECT table_name FROM information_schema.tables WHERE table_schema = DATABASE()');
  const names = new Set(tables.map((row) => row.TABLE_NAME || row.table_name));
  const required = [
    'employees','system_settings','attendance_records','leave_requests','wfh_requests',
    'attendance_correction_requests','flex_start_requests','notifications','audit_logs',
    'company_holidays','attachments','qr_challenges','qr_challenge_uses','temporary_exits',
    'employee_schedule_exceptions','employee_emergency_contacts','employment_history','onboarding_tasks',
    'employee_documents','company_assets','company_policies','policy_acknowledgements','separation_cases','schema_migrations'
  ];
  for (const table of required) assert.ok(names.has(table), `Missing required table: ${table}`);

  const [migrationRows] = await pool.query('SELECT version, checksum FROM schema_migrations ORDER BY version');
  assert.ok(migrationRows.some((row) => row.version === '001_initial_schema.sql'), 'Initial schema migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '002_session_revocation.sql'), 'Session revocation migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '003_retire_qr_setting.sql'), 'QR retirement migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '004_employee_profile_organization.sql'), 'Employee profile organization migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '005_holiday_types.sql'), 'Holiday type migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '006_enterprise_hr.sql'), 'Enterprise HR/policy center migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '007_wifi_attendance_method.sql'), 'Wi-Fi attendance method migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '008_attendance_workflow_integrity.sql'), 'Attendance workflow integrity migration is not recorded');
  assert.ok(migrationRows.some((row) => row.version === '009_enterprise_history_nullable_creator.sql'), 'Enterprise history creator hardening migration is not recorded');
  assert.ok(migrationRows.every((row) => /^[a-f0-9]{64}$/.test(String(row.checksum || ''))), 'Every applied migration must have a SHA-256 checksum');

  const [historyCreator] = await pool.query(`SELECT IS_NULLABLE AS is_nullable FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name='employment_history' AND column_name='created_by'`);
  assert.equal(historyCreator.length, 1, 'Employment-history created_by column is missing');
  assert.equal(String(historyCreator[0].is_nullable).toUpperCase(), 'YES', 'Unknown historical creator must be nullable');

  const [activeDateColumn] = await pool.query(`SELECT EXTRA AS extra, GENERATION_EXPRESSION AS generation_expression FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name='wfh_requests' AND column_name='active_request_date'`);
  assert.equal(activeDateColumn.length, 1, 'WFH active-request generated date column is missing');
  assert.match(String(activeDateColumn[0].extra).toLowerCase(), /stored generated/, 'WFH active-request date must be stored/generated by MySQL');
  assert.match(String(activeDateColumn[0].generation_expression).toUpperCase(), /PENDING/);
  assert.match(String(activeDateColumn[0].generation_expression).toUpperCase(), /APPROVED/);

  const [wfhIndexes] = await pool.query(`SELECT INDEX_NAME AS index_name, NON_UNIQUE AS non_unique, GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) AS columns_used FROM information_schema.statistics WHERE table_schema=DATABASE() AND table_name='wfh_requests' GROUP BY index_name, non_unique`);
  const activeWfhIndex = wfhIndexes.find((row) => row.index_name === 'uq_wfh_active_employee_day');
  assert.ok(activeWfhIndex, 'Unique active WFH-per-day index is missing');
  assert.equal(Number(activeWfhIndex.non_unique), 0, 'Active WFH-per-day index must be unique');
  assert.equal(activeWfhIndex.columns_used, 'employee_id,active_request_date');
  assert.ok(!wfhIndexes.some((row) => row.index_name === 'uq_wfh_employee_day'), 'Legacy all-status WFH uniqueness index should be replaced');

  const [wfhForeignKeys] = await pool.query(`SELECT CONSTRAINT_NAME AS constraint_name FROM information_schema.referential_constraints WHERE constraint_schema=DATABASE() AND table_name='wfh_requests' AND constraint_name='fk_wfh_employee_active'`);
  assert.equal(wfhForeignKeys.length, 1, 'WFH employee foreign key is missing');

  const [attendanceMethods] = await pool.query(`SELECT COLUMN_NAME AS column_name, COLUMN_TYPE AS column_type FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name='attendance_records' AND column_name IN ('check_in_method','check_out_method')`);
  assert.equal(attendanceMethods.length, 2, 'Attendance method columns are missing');
  for (const column of attendanceMethods) {
    assert.match(column.column_type, /WIFI/, `${column.column_name} must support Wi-Fi attendance`);
    assert.match(column.column_type, /OFF_PREMISES/, `${column.column_name} must support off-premises checkout`);
  }

  const [employeeRows] = await pool.query("SELECT COUNT(*) AS total FROM employees WHERE status='ACTIVE'");
  assert.ok(Number(employeeRows[0].total) >= 11, 'Expected seeded local workforce plus administrator');

  const [settings] = await pool.query("SELECT setting_value FROM system_settings WHERE setting_key='geofence_meters'");
  assert.equal(Number(settings[0]?.setting_value), 80, 'Locked 80m geofence setting is missing');
  const [qrSetting] = await pool.query("SELECT COUNT(*) AS total FROM system_settings WHERE setting_key='qr_ttl_seconds'");
  assert.equal(Number(qrSetting[0].total), 0, 'Retired QR setting is still present');

  console.log('Database smoke verification: PASS');
} finally {
  await pool.end();
}
