CREATE TABLE IF NOT EXISTS email_outbox (
  id CHAR(36) NOT NULL PRIMARY KEY,
  dedupe_key VARCHAR(191) NOT NULL,
  recipients_json JSON NOT NULL,
  subject VARCHAR(255) NOT NULL,
  text_body MEDIUMTEXT NOT NULL,
  html_body MEDIUMTEXT NOT NULL,
  reply_to VARCHAR(320) NULL,
  from_name VARCHAR(120) NULL,
  status ENUM('PENDING','PROCESSING','SENT','FAILED') NOT NULL DEFAULT 'PENDING',
  attempts INT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts INT UNSIGNED NOT NULL DEFAULT 8,
  available_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  locked_at DATETIME(3) NULL,
  lease_until DATETIME(3) NULL,
  lock_token CHAR(36) NULL,
  last_error VARCHAR(1000) NULL,
  sent_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_email_outbox_dedupe_key (dedupe_key),
  KEY ix_email_outbox_due (status, available_at, created_at),
  KEY ix_email_outbox_lease (status, lease_until)
) ENGINE=InnoDB;
